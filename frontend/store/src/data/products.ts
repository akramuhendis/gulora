export interface Product {
  id: string;
  name: string;
  slug: string;
  price: number;
  originalPrice?: number;
  discount?: number;
  rating: number;
  reviewCount: number;
  image: string;
  images: string[];
  category: string;
  categorySlug: string;
  tags: string[];
  badge?: string;
  isSameDay: boolean;
  isFreeDelivery: boolean;
  description: string;
  stock: number;
  /** API ilə yüklənəndə əlavə olunur (oxşar məhsullar üçün filtr). */
  backendCategoryId?: string;
  /** Mağaza vitrini (backend sellerShop). */
  sellerShop?: {
    sellerUserId: string;
    storeName: string;
    storeSlug: string;
    logoUrl?: string | null;
  };
  /** Aktiv satıcı kampaniyası (məhsul detalı API). */
  sellerCampaign?: {
    name: string;
    percent: number;
    priceAfterDiscount: number;
    minimumCartAmount?: number | null;
    /** Backend: discount | shipping (çatdırılma — vitrin qiymətini dəyişmir). */
    kind?: "discount" | "shipping";
  };
}

